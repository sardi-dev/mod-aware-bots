#!/usr/bin/env python3
"""Write the price table the module loads: one row per tradable item with its class and (min, max) in copper.

usage: export_price_table.py DB_FILE OUT_SQL

The output goes to data/sql/db-world/ of the module as a new, dated file (design decision 0028: the core updater applies each
file once and applied files are never edited, so a retune is a new file). The file creates `playerbots_item_price` in the
world database if it is missing and replaces its rows; the module reads it once at start when
`AiPlayerbot.Auction.Enable = 1` (src/Manager/PriceTable.cpp). Items whose maximum is above the trading cap (10,000
gold) are left out: bots never trade them. Prices fit an unsigned 32-bit column. The output is deterministic: the same
database gives the same bytes.
"""
import sqlite3
import sys

# Must match enum class PricePolicy::PriceClass in src/Utils/PricePolicy.h (tests/test_price_policy.cpp checks the C++ side).
PRICE_CLASS_IDS = {
    'vendor': 1, 'gathered': 2, 'crafted': 3, 'recipe': 4, 'world_normal': 5, 'world_elite': 6, 'world_rare': 7,
    'world_chest': 8, 'dungeon_trash': 9, 'dungeon_boss': 10, 'raid_trash': 11, 'raid_boss': 12, 'container': 13,
    'quest_reward': 14, 'vendor_token': 15, 'other': 16,
}
UINT32_MAX = 4294967295
TRADE_CAP_COPPER = 100000000   # items whose maximum is above 10,000 gold are never traded by bots (PricePolicy::TRADE_CAP_COPPER)
ROWS_PER_INSERT = 500

HEADER = """-- Price ranges of the bots' auction house (design decision 0034; mod-aware-bots-548 docs/economy/pricing-audit.md).
-- One row per item that can be listed: price_class (1 vendor .. 16 other, see PricePolicy::PriceClass), and the lowest and
-- highest price in copper per unit. Generated by tools/economy/export_price_table.py from the 5.4.8 world data; do not
-- edit by hand. The module reads the table once at start, and only while AiPlayerbot.Auction.Enable = 1. Safe to run
-- again (it replaces the rows); uninstall/world_item_price_remove.sql drops the table.
"""


def render(rows):
    """The SQL text for rows of (item, price_class, lo, hi), items sorted, classes by name."""
    out = [HEADER,
           'CREATE TABLE IF NOT EXISTS `playerbots_item_price` (\n'
           '  `item` int unsigned NOT NULL,\n'
           '  `price_class` tinyint unsigned NOT NULL,\n'
           '  `min_price` int unsigned NOT NULL,\n'
           '  `max_price` int unsigned NOT NULL,\n'
           '  PRIMARY KEY (`item`)\n'
           ') ENGINE=MyISAM DEFAULT CHARSET=utf8;\n'
           'DELETE FROM `playerbots_item_price`;\n']
    for start in range(0, len(rows), ROWS_PER_INSERT):
        values = ',\n'.join('({},{},{},{})'.format(i, PRICE_CLASS_IDS[c], min(lo, UINT32_MAX), min(hi, UINT32_MAX))
                            for i, c, lo, hi in rows[start:start + ROWS_PER_INSERT])
        out.append('INSERT INTO `playerbots_item_price` VALUES\n{};\n'.format(values))
    return ''.join(out)


def select_rows(con):
    return con.execute('SELECT item, price_class, lo, hi FROM item_price WHERE hi <= ? AND lo > 0 AND lo <= hi ORDER BY item',
                       (TRADE_CAP_COPPER,)).fetchall()


def main():
    rows = select_rows(sqlite3.connect(sys.argv[1]))
    with open(sys.argv[2], 'w') as out:
        out.write(render(rows))
    print('{} rows'.format(len(rows)))


if __name__ == '__main__':
    main()
