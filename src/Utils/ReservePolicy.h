#ifndef MOD_AWARE_BOTS_RESERVEPOLICY_H
#define MOD_AWARE_BOTS_RESERVEPOLICY_H

#include "BotSalePolicy.h"
#include "PricePolicy.h"
#include "ReserveTable.h"

#include <algorithm>
#include <cstdint>

// Pure rules of the gold a random bot keeps before the auction house may spend any (design decision 0033 point 6, owner answer
// 2026-11-22: "add a training and mount fund"). The reserve is
//
//   the repair reserve (BotSalePolicy::PurchaseReserve, unchanged)
//   + the training fund: the trainer spells it will want in the next few levels
//   + the next riding skill it does not have yet
//   + a mount, when it has none and is about to want one
//
// Costs come from the 5.4.8 trainer and vendor data (ReserveTable.h, generated by tools/economy/export_reserve_table.py),
// so no number here is a guess. No game core is used: the caller (the auction house errand) reads the bot into Facts.
//
// What a bot really pays for today (design decision 0016 and 0017, BotTraining): random bots learn their class spells for free at
// each level-up (AiPlayerbot.AutoLearnTrainerSpells), so that part of the fund applies only when that setting is off. They
// pay for profession ranks and riding. Recipes are not part of the goals: a crafter keeps a separate share of its spare gold
// for them (owner answer 2026-11-22, see docs/economy/reserve-fund.md).
namespace ReservePolicy
{
// "The next few levels" of the owner's answer: spells and steps needing at most this many levels above the bot's own.
constexpr uint32_t DEFAULT_LOOKAHEAD_LEVELS = 5;
constexpr uint32_t MAX_LOOKAHEAD_LEVELS = 20;

// The fund is capped at this share of the gold above the repair reserve, so a bot saving for a 5,000 gold riding skill is
// not locked out of the house for good while it holds a few hundred (it keeps this share for the goal and may spend a
// quarter of the rest per visit). 100 reserves the whole fund, which the owner's literal rule asks for. Owner answer
// 2026-11-22: 75 (the recommended 50 was not taken).
constexpr uint32_t DEFAULT_GOAL_SHARE_PERCENT = 75;

// A bot with a primary crafting profession also keeps this share of the gold above the repair reserve for recipes (owner
// answer 2026-11-22: "a share for crafters"). It is separate from the goal share: the two never add up to more than 100
// percent of the spare gold (the recipe share is cut to what the goal share leaves), so 10 leaves a crafter at the default
// goal share with 15 percent of its spare gold that is neither reserved nor spent per visit above the usual quarter.
// 10 is about what the green recipes cost: for the median bot at levels 40 and 60 (44 and 78 gold) it is 4 to 8 gold,
// against 3 to 8 gold of green recipes at skill 200 and 9 to 46 gold at 275 (docs/economy/reserve-fund.md, section 3).
constexpr uint32_t DEFAULT_RECIPE_SHARE_PERCENT = 10;

// The recipe share never holds more than this much: 700 gold, a little above what all the green recipes of one profession
// cost at skill 425 (654 gold, reserve-fund.md section 3), so a rich crafter does not sit on a hoard for recipes.
constexpr uint64_t MAX_RECIPE_RESERVE_COPPER = 700ull * 10000ull;

// Profession skill lines that count as crafting (SharedDefines.h SKILL_*): alchemy, blacksmithing, enchanting, engineering,
// inscription, jewelcrafting, leatherworking and tailoring. Herbalism, mining and skinning are gathering and do not.
constexpr uint32_t CRAFTING_SKILLS[] = { 164, 165, 171, 197, 202, 333, 755, 773 };

constexpr bool IsCraftingSkill(uint32_t skillId)
{
    for (uint32_t const crafting : CRAFTING_SKILLS)
        if (crafting == skillId)
            return true;
    return false;
}

// A bot practises at most this many professions that count for the fund (two primary and two secondary).
constexpr uint32_t MAX_COUNTED_PROFESSIONS = 4;

struct Facts
{
    uint32_t level = 0;
    uint32_t classId = 0;                   // 1 to 11
    bool classSpellsPaid = false;           // true when AiPlayerbot.AutoLearnTrainerSpells is off
    uint64_t pendingClassTrainCopper = 0;   // the "train cost" value: class spells learnable now (used only when paid)
    uint32_t professionCount = 0;           // professions the bot practises or will learn (primary and secondary)
    uint32_t craftingProfessionCount = 0;   // primary professions among them that craft (IsCraftingSkill), not gathering
    uint32_t ridingSkill = 0;               // SKILL_RIDING, pure value
    bool knowsFlightLicence = false;
    bool knowsMount = false;
};

struct Params
{
    uint32_t lookaheadLevels = DEFAULT_LOOKAHEAD_LEVELS;
    uint32_t goalSharePercent = DEFAULT_GOAL_SHARE_PERCENT;
    uint32_t recipeSharePercent = DEFAULT_RECIPE_SHARE_PERCENT;
};

// What the bot wants to keep, by purpose, before the share cap.
struct Goals
{
    uint64_t classSpells = 0;
    uint64_t professionRanks = 0;
    uint64_t riding = 0;
    uint64_t mount = 0;

    uint64_t Total() const { return classSpells + professionRanks + riding + mount; }
};

struct Reserve
{
    uint64_t repair = 0;
    Goals goals;
    uint64_t heldForGoals = 0;   // the part of the goals actually kept back, after the share cap
    uint64_t heldForRecipes = 0; // a crafter's separate part for profession recipes; 0 for a bot with no crafting profession

    uint64_t Total() const { return repair + heldForGoals + heldForRecipes; }
};

namespace detail
{
inline uint32_t Lookahead(Params const& params) { return std::min(params.lookaheadLevels, MAX_LOOKAHEAD_LEVELS); }

inline uint32_t TableLevel(uint64_t level) { return uint32_t(std::min<uint64_t>(level, ReserveTable::MAX_LEVEL)); }

// A step or spell "in the window": above the bot's level (it is the future part) up to lookahead levels higher.
constexpr bool InWindow(uint32_t level, uint32_t needsLevel, uint32_t lookahead)
{
    return needsLevel > level && needsLevel <= uint64_t(level) + lookahead;
}
}  // namespace detail

// Class trainer spells needing more than `level` and at most `level + lookahead`, plus what is learnable now.
inline uint64_t ClassSpellGoal(Facts const& facts, Params const& params)
{
    if (!facts.classSpellsPaid || facts.classId == 0 || facts.classId >= ReserveTable::CLASS_SLOTS)
        return 0;

    uint32_t const from = detail::TableLevel(facts.level);
    uint32_t const to = detail::TableLevel(uint64_t(facts.level) + detail::Lookahead(params));
    uint64_t const window = ReserveTable::CLASS_SPELL_COST[facts.classId][to] - ReserveTable::CLASS_SPELL_COST[facts.classId][from];
    return window + facts.pendingClassTrainCopper;
}

// The next rank of each profession the bot practises that falls in the window.
inline uint64_t ProfessionRankGoal(Facts const& facts, Params const& params)
{
    uint64_t sum = 0;
    for (ReserveTable::RankStep const& rank : ReserveTable::PROFESSION_RANKS)
        if (detail::InWindow(facts.level, rank.level, detail::Lookahead(params)))
            sum += rank.cost;

    return sum * std::min(facts.professionCount, MAX_COUNTED_PROFESSIONS);
}

// Index into RIDING_STEPS of the first step the bot does not have yet, or -1 when it has them all.
inline int NextRidingStep(uint32_t ridingSkill, bool knowsFlightLicence)
{
    int index = 0;
    for (ReserveTable::RidingStep const& step : ReserveTable::RIDING_STEPS)
    {
        bool const have = step.skillGiven ? ridingSkill >= step.skillGiven : knowsFlightLicence;
        if (!have)
            return index;
        ++index;
    }
    return -1;
}

// The next riding step's price once the bot is within the lookahead of the level it needs (or past it).
inline uint64_t RidingGoal(Facts const& facts, Params const& params)
{
    int const next = NextRidingStep(facts.ridingSkill, facts.knowsFlightLicence);
    if (next < 0)
        return 0;

    ReserveTable::RidingStep const& step = ReserveTable::RIDING_STEPS[next];
    return uint64_t(step.level) <= uint64_t(facts.level) + detail::Lookahead(params) ? step.cost : 0;
}

// The cheapest vendor mount, for a bot with none that is close to the level the first one needs.
inline uint64_t MountGoal(Facts const& facts, Params const& params)
{
    if (facts.knowsMount)
        return 0;

    return uint64_t(ReserveTable::MOUNT_LEVEL) <= uint64_t(facts.level) + detail::Lookahead(params) ? ReserveTable::MOUNT_PRICE : 0;
}

inline Goals ComputeGoals(Facts const& facts, Params const& params)
{
    Goals goals;
    goals.classSpells = ClassSpellGoal(facts, params);
    goals.professionRanks = ProfessionRankGoal(facts, params);
    goals.riding = RidingGoal(facts, params);
    goals.mount = MountGoal(facts, params);
    return goals;
}

// The part of the spare gold left for recipes once the goal share is taken: the two shares together never pass 100 percent.
inline uint32_t RecipeSharePercentFor(Params const& params)
{
    uint32_t const goal = std::min<uint32_t>(params.goalSharePercent, 100);
    return std::min<uint32_t>(params.recipeSharePercent, 100 - goal);
}

// What a crafter keeps for recipes: its share of the gold above the repair reserve, at most MAX_RECIPE_RESERVE_COPPER.
inline uint64_t RecipeHold(Facts const& facts, Params const& params, uint64_t spare)
{
    if (facts.craftingProfessionCount == 0)
        return 0;

    return std::min(PricePolicy::PercentOf(spare, RecipeSharePercentFor(params)), MAX_RECIPE_RESERVE_COPPER);
}

// The reserve for a bot holding `money` copper. The goals are kept back up to goalSharePercent of the money above the
// repair reserve and a crafter keeps recipeSharePercent more for recipes (never more than 100 percent together); the
// caller computes this once on arrival and keeps the result for the whole visit.
inline Reserve ComputeReserve(Facts const& facts, Params const& params, uint64_t money)
{
    Reserve reserve;
    reserve.repair = BotSalePolicy::PurchaseReserve(facts.level);
    reserve.goals = ComputeGoals(facts, params);

    uint64_t const spare = money > reserve.repair ? money - reserve.repair : 0;
    uint64_t const cap = PricePolicy::PercentOf(spare, std::min<uint32_t>(params.goalSharePercent, 100));
    reserve.heldForGoals = std::min(reserve.goals.Total(), cap);
    reserve.heldForRecipes = RecipeHold(facts, params, spare);
    return reserve;
}

// What a recipe purchase (a vendor today, the auction house later) may spend now: the recipe part, and never gold below the
// repair reserve. Purchases of anything else keep the whole reserve, recipes included, through the visit's wallet.
inline uint64_t RecipeBudget(Reserve const& reserve, uint64_t moneyNow)
{
    uint64_t const aboveRepair = moneyNow > reserve.repair ? moneyNow - reserve.repair : 0;
    return std::min(reserve.heldForRecipes, aboveRepair);
}

// ---------------------------------------------------------------------------------------------------------------
// The money of one visit to the auction house. Purchases keep the whole reserve; a deposit is what a bot pays to earn, so
// it is held back only by the repair reserve, or a bot saving for a riding skill could never list the goods that pay for it.
// Both draw on the same quarter of the visit's gold: a deposit counts as spending against the purchase budget.
// ---------------------------------------------------------------------------------------------------------------
struct VisitMoney
{
    PricePolicy::Wallet wallet;     // the purchase budget: 25 percent of the gold above the full reserve
    uint64_t reserve = 0;           // the full reserve, fixed on arrival
    uint64_t repairReserve = 0;
    uint64_t depositBudget = 0;     // 25 percent of the gold above the repair reserve
    uint64_t depositsSpent = 0;
};

inline VisitMoney MakeVisitMoney(uint64_t moneyOnArrival, Reserve const& reserve)
{
    VisitMoney visit;
    visit.reserve = reserve.Total();
    visit.repairReserve = reserve.repair;
    visit.wallet = PricePolicy::MakeWallet(moneyOnArrival, visit.reserve);
    visit.depositBudget = moneyOnArrival > reserve.repair
                              ? PricePolicy::PercentOf(moneyOnArrival - reserve.repair, PricePolicy::VISIT_SPEND_PERCENT)
                              : 0;
    return visit;
}

// What the bot may still pay in deposits right now: the visit's share and the repair reserve both hold.
inline uint64_t DepositLeft(VisitMoney const& visit, uint64_t moneyNow)
{
    uint64_t const byBudget = visit.depositBudget > visit.depositsSpent ? visit.depositBudget - visit.depositsSpent : 0;
    uint64_t const byMoney = moneyNow > visit.repairReserve ? moneyNow - visit.repairReserve : 0;
    return std::min(byBudget, byMoney);
}

// Records a deposit when it fits; false and no change otherwise.
inline bool SpendDeposit(VisitMoney& visit, uint64_t moneyNow, uint64_t amount)
{
    if (amount > DepositLeft(visit, moneyNow))
        return false;

    visit.depositsSpent += amount;
    visit.wallet.committed += amount;
    return true;
}

// Purchases (bids and buyouts) use the wallet of PricePolicy with the full reserve.
inline bool CanBuy(VisitMoney const& visit, uint64_t moneyNow, uint64_t amount)
{
    return PricePolicy::CanSpend(visit.wallet, moneyNow, visit.reserve, amount);
}

inline bool SpendPurchase(VisitMoney& visit, uint64_t moneyNow, uint64_t amount)
{
    return PricePolicy::Spend(visit.wallet, moneyNow, visit.reserve, amount);
}
}  // namespace ReservePolicy

#endif
